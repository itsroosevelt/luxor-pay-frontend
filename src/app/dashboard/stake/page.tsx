'use client';

import React, { useState } from 'react';
import { Lock, ShieldCheck, RefreshCw, CheckCircle2 } from 'lucide-react';

const POOLS = {
  lxr: { symbol: 'LXR', name: 'Luxor Protocol Staking (LXR)', desc: 'Stake LXR to earn a share of protocol transaction fees generated by Luxor Pay.', apy: 0.182 },
  sol: { symbol: 'SOL', name: 'Liquid SOL Staking (lstSOL)', desc: 'Liquid staking delegated directly to top-tier reputational validators on Solana.', apy: 0.074 },
} as const;

export default function StakePage() {
  const [stakeAmount, setStakeAmount] = useState('100');
  const [selectedPool, setSelectedPool] = useState<'lxr' | 'sol'>('lxr');
  const [isStaking, setIsStaking] = useState(false);
  const [stakedSuccess, setStakedSuccess] = useState(false);

  const handleStake = (e: React.FormEvent) => {
    e.preventDefault();
    setIsStaking(true);
    setTimeout(() => {
      setIsStaking(false);
      setStakedSuccess(true);
    }, 1200);
  };

  return (
    <>
      <header className="lx-page-header">
        <h1 className="lx-page-title">Stake &amp; Staking Yield</h1>
        <p className="lx-page-subtitle">Secure the network and earn on-chain yields with your LXR and SOL assets.</p>
      </header>

      <div className="mx-auto w-full max-w-[1200px] space-y-6 p-6 md:p-8">
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {(Object.keys(POOLS) as Array<keyof typeof POOLS>).map((key) => {
            const pool = POOLS[key];
            const active = selectedPool === key;
            return (
              <button
                key={key}
                type="button"
                onClick={() => setSelectedPool(key)}
                className="lx-card text-left transition-colors"
                style={active ? { borderColor: 'var(--lx-border-strong)', background: 'var(--lx-surface-hover)' } : undefined}
              >
                <div className="flex items-start justify-between mb-3">
                  <span className="flex h-9 w-9 items-center justify-center rounded-lg text-xs font-semibold" style={{ background: 'var(--lx-fill)', border: '1px solid var(--lx-border)', color: 'var(--lx-text)' }}>
                    {pool.symbol}
                  </span>
                  <span className="lx-status">{(pool.apy * 100).toFixed(1)}% APY</span>
                </div>
                <h3 className="text-sm font-semibold" style={{ color: 'var(--lx-text)' }}>{pool.name}</h3>
                <p className="mt-1 text-xs" style={{ color: 'var(--lx-text-dim)' }}>{pool.desc}</p>
              </button>
            );
          })}
        </div>

        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
          <div className="lg:col-span-7 lx-card space-y-5">
            <div className="flex items-center gap-2">
              <Lock size={18} style={{ color: 'var(--lx-text-muted)' }} />
              <h2 className="text-[15px] font-semibold" style={{ color: 'var(--lx-text)' }}>Deposit into Staking</h2>
            </div>

            <form onSubmit={handleStake} className="space-y-4">
              <div>
                <div className="mb-1.5 flex justify-between text-xs font-medium" style={{ color: 'var(--lx-text-muted)' }}>
                  <span>Deposit Amount</span>
                  <span style={{ color: 'var(--lx-text-dim)' }}>Balance: 1,500 {POOLS[selectedPool].symbol}</span>
                </div>
                <div className="relative">
                  <input
                    type="number"
                    value={stakeAmount}
                    onChange={(e) => setStakeAmount(e.target.value)}
                    className="w-full rounded-lg px-3.5 py-3 pr-16 text-sm font-mono outline-none"
                    style={{ background: 'var(--lx-surface-2)', border: '1px solid var(--lx-border)', color: 'var(--lx-text)' }}
                  />
                  <button
                    type="button"
                    onClick={() => setStakeAmount('1500')}
                    className="absolute right-2.5 top-1/2 -translate-y-1/2 rounded-md px-2 py-1 text-[11px] font-semibold"
                    style={{ background: 'var(--lx-fill)', border: '1px solid var(--lx-border)', color: 'var(--lx-text-muted)' }}
                  >
                    MAX
                  </button>
                </div>
              </div>

              <dl className="flex items-center justify-between text-xs pt-3" style={{ borderTop: '1px solid var(--lx-border)' }}>
                <div>
                  <dt style={{ color: 'var(--lx-text-dim)' }}>Estimated Annual Yield</dt>
                  <dd className="font-mono font-medium" style={{ color: 'var(--lx-text)' }}>
                    +{(Number(stakeAmount || 0) * POOLS[selectedPool].apy).toFixed(2)} {POOLS[selectedPool].symbol}
                  </dd>
                </div>
                <div className="text-right">
                  <dt style={{ color: 'var(--lx-text-dim)' }}>Unlocking Period</dt>
                  <dd className="font-medium" style={{ color: 'var(--lx-text)' }}>No lockup (instant withdrawal)</dd>
                </div>
              </dl>

              <button type="submit" disabled={isStaking} className="lx-btn lx-btn-primary w-full justify-center py-2.5">
                {isStaking ? <><RefreshCw size={15} className="animate-spin" /> Processing…</> : `Confirm Staking ${POOLS[selectedPool].symbol}`}
              </button>
            </form>

            {stakedSuccess && (
              <p className="flex items-center gap-2 text-sm" style={{ color: 'var(--lx-text)' }}>
                <CheckCircle2 size={16} /> Staking completed. Your rewards have started accumulating on-chain.
              </p>
            )}
          </div>

          <div className="lg:col-span-5 lx-card space-y-4">
            <div className="flex items-center gap-2">
              <ShieldCheck size={16} style={{ color: 'var(--lx-text-muted)' }} />
              <h3 className="lx-eyebrow">Position Summary</h3>
            </div>
            <dl className="space-y-2.5 text-sm">
              <div className="flex items-center justify-between">
                <dt style={{ color: 'var(--lx-text-dim)' }}>Staked LXR</dt>
                <dd className="font-mono font-medium" style={{ color: 'var(--lx-text)' }}>5,000.00 LXR</dd>
              </div>
              <div className="flex items-center justify-between">
                <dt style={{ color: 'var(--lx-text-dim)' }}>Earned Rewards</dt>
                <dd className="font-mono font-medium" style={{ color: 'var(--lx-text)' }}>+$240.50 USD</dd>
              </div>
            </dl>
          </div>
        </div>
      </div>
    </>
  );
}
