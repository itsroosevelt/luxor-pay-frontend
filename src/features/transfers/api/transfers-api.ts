import { bearerAuth } from '@/lib/auth-client';
import { getWalletAuthHeaders, type WalletSigner } from '@/lib/wallet-session';
import { apiUrl } from '@/lib/api-client';

export interface Transfer {
  id: string;
  merchantId: string;
  fromWallet: string;
  toWallet: string;
  reference: string | null;
  toNickname: string | null;
  mint: string;
  symbol: string | null;
  decimals: number;
  amount: string;
  rawAmount: string;
  signature: string | null;
  status: string;
  errorMessage: string | null;
  createdAt: string;
  confirmedAt: string | null;
}

export interface TransfersResponse {
  data: Transfer[];
  total: number;
  totalPages: number;
}

export async function getTransfers(
  offset: number = 0,
  limit: number = 10,
  status?: string
): Promise<TransfersResponse> {
  const url = new URL(apiUrl('/transfers'));
  url.searchParams.append('offset', offset.toString());
  url.searchParams.append('limit', limit.toString());
  if (status) {
    url.searchParams.append('status', status);
  }

  const res = await fetch(url.toString(), {
    headers: {
      ...(await bearerAuth()),
      'Content-Type': 'application/json',
    },
  });

  const json = await res.json();

  if (!res.ok) {
    const errorMsg =
      (Array.isArray(json?.message) ? json.message[0] : json?.message) ||
      json?.error ||
      'Failed to fetch transfers';
    throw new Error(errorMsg);
  }

  return json as TransfersResponse;
}

/**
 * Returns the creation date of the merchant's oldest transaction (sent or
 * received), or null when the account has no transactions yet. Transactions
 * are returned newest-first, so the oldest record sits at the last offset.
 */
export async function getEarliestTransferDate(): Promise<Date | null> {
  const first = await getTransfers(0, 1);
  if (!first.total || first.total === 0) return null;

  const last = await getTransfers(first.total - 1, 1);
  const oldest = last.data?.[0];
  if (!oldest?.createdAt) return null;

  const date = new Date(oldest.createdAt);
  return Number.isNaN(date.getTime()) ? null : date;
}

/**
 * Fetches the multi-currency account statement PDF generated by the backend
 * (the exact same document that is delivered by email) for a given month.
 *
 * The backend must expose `GET /transfers/statement-pdf-multi?year=&month=`
 * returning `Content-Type: application/pdf` scoped to the authenticated
 * merchant. Returns the raw PDF as a Blob.
 */
export async function getStatementPdfBlob(
  year: number,
  month: number
): Promise<Blob> {
  const url = new URL(apiUrl('/transfers/statement-pdf-multi'));
  url.searchParams.set('year', String(year));
  url.searchParams.set('month', String(month));

  const res = await fetch(url.toString(), {
    headers: { ...(await bearerAuth()) },
  });

  if (!res.ok) {
    let message = 'Failed to load the account statement PDF.';
    try {
      const json = await res.json();
      message = json.message || json.error || message;
    } catch {
      // Non-JSON error body; keep the default message.
    }
    throw new Error(message);
  }

  const blob = await res.blob();
  if (blob.type && !blob.type.includes('pdf')) {
    // Backend returned something that is not a PDF (e.g. an error page).
    const text = await blob.text().catch(() => '');
    throw new Error(text || 'The account statement response was not a PDF.');
  }
  return blob;
}

export interface SendTransferPayload {
  toWallet: string;
  amount: string;
  mint?: string | null;
  toNickname?: string | null;
  reference?: string;
  fromVaultPda?: string;
  fromVaultId?: string;
  transactionTypeId?: 'Regular' | 'Request' | 'TopUp';
  paymentRequestId?: string;
  /** WGS-84 latitude in decimal degrees (-90 to 90). */
  latitude?: number;
  /** WGS-84 longitude in decimal degrees (-180 to 180). */
  longitude?: number;
}

/** `wallet`: connected member wallet — custodial outflows must carry its signed session. */
export async function sendTransfer(payload: SendTransferPayload, wallet: WalletSigner): Promise<{ data: Transfer }> {
  const walletHeaders = await getWalletAuthHeaders(wallet);
  const response = await fetch(apiUrl('/transfers/send'), {
    method: 'POST',
    headers: {
      ...(await bearerAuth()),
      ...walletHeaders,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(payload),
  });

  const json = await response.json();

  if (!response.ok) {
    let errorMessage = 'Failed to process transfer';
    if (Array.isArray(json.message)) {
      errorMessage = json.message.join(', ');
    } else if (json.message) {
      errorMessage = json.message;
    } else if (json.error) {
      errorMessage = json.error;
    }
    throw new Error(errorMessage);
  }

  return json as { data: Transfer };
}

