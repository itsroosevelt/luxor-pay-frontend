import jsPDF from "jspdf";
import { Transfer } from "@/features/transfers/api/transfers-api";

/**
 * Generates and downloads an official SterlingPay PDF receipt for a transaction.
 */
export function downloadTransactionReceipt(
  transfer: Transfer,
  symbol: string = "SOL",
  merchantWallet: string | null = null
) {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const isSent = merchantWallet ? transfer.fromWallet === merchantWallet : false;
  const typeText = isSent ? "Sent Payment" : "Received Payment";

  const pageWidth = doc.internal.pageSize.getWidth();

  // Dark background canvas
  doc.setFillColor(10, 10, 10);
  doc.rect(0, 0, pageWidth, 297, "F");

  // Receipt Box Card
  doc.setFillColor(18, 18, 18);
  doc.setDrawColor(40, 40, 40);
  doc.roundedRect(15, 15, pageWidth - 30, 245, 6, 6, "FD");

  // Brand Header
  doc.setFont("helvetica", "bold");
  doc.setFontSize(26);
  doc.setTextColor(37, 99, 235); // Sterling blue #2563EB
  doc.text("SterlingPay", pageWidth / 2, 35, { align: "center" });

  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.setTextColor(160, 160, 160);
  doc.text("Official On-Chain Settlement Receipt", pageWidth / 2, 43, { align: "center" });

  // Divider
  doc.setDrawColor(50, 50, 50);
  doc.setLineWidth(0.4);
  doc.line(25, 50, pageWidth - 25, 50);

  // Status Color
  const statusUpper = (transfer.status || "").toUpperCase();
  let statusColor: [number, number, number] = [52, 211, 153]; // Green #34D399
  if (statusUpper.includes("FAIL") || statusUpper.includes("REJECT")) {
    statusColor = [239, 68, 68]; // Red #EF4444
  } else if (statusUpper.includes("PENDING") || statusUpper.includes("PROCESSING")) {
    statusColor = [96, 165, 250]; // Blue #60A5FA
  }

  // Row Generator
  let y = 65;
  const leftX = 30;
  const rightX = pageWidth - 30;

  const addRow = (label: string, value: string, isBold: boolean = false, customColor?: [number, number, number]) => {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(120, 120, 120);
    doc.text(label.toUpperCase(), leftX, y);

    doc.setFont("helvetica", isBold ? "bold" : "normal");
    doc.setFontSize(11);
    doc.setTextColor(...(customColor || [240, 240, 240]));

    const splitValue = doc.splitTextToSize(value, 105);
    doc.text(splitValue, rightX, y, { align: "right" });

    const lines = Array.isArray(splitValue) ? splitValue.length : 1;
    y += 14 + (lines - 1) * 6;
  };

  addRow("Transaction ID", transfer.id);
  addRow("Type", typeText);
  addRow("Status", statusUpper, true, statusColor);
  addRow("Amount", `${transfer.amount} ${symbol}`, true, [255, 255, 255]);
  addRow("From Address", transfer.fromWallet || "N/A");
  addRow("To Address", transfer.toWallet || "N/A");
  if (transfer.reference) {
    addRow("Reference ID", transfer.reference);
  }
  addRow("Created Date", new Date(transfer.createdAt).toLocaleString("en-US"));
  if (transfer.confirmedAt) {
    addRow("Confirmed Date", new Date(transfer.confirmedAt).toLocaleString("en-US"));
  }
  if (transfer.signature) {
    addRow("Transaction Hash", transfer.signature);
  }

  // Footer
  doc.setDrawColor(40, 40, 40);
  doc.line(25, 235, pageWidth - 25, 235);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100, 100, 100);
  doc.text("Generated by SterlingPay Settlement Protocol • www.sterlingpay.com", pageWidth / 2, 243, { align: "center" });

  doc.save(`Transaction_Receipt_${transfer.id.slice(0, 8)}.pdf`);
}
